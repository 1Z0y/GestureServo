void OLED_Init(void) {
	#ifdef USE_MOCK
    // 无需操作
#else
    // SSD1306 128x32 初始化序列
    OLED_WriteCmd(0xAE); // display off
    OLED_WriteCmd(0x20); OLED_WriteCmd(0x00); // 水平寻址模式
    OLED_WriteCmd(0xb0); // 页起始
    OLED_WriteCmd(0xc8); // COM 扫描方向
    OLED_WriteCmd(0x00); // 列低地址
    OLED_WriteCmd(0x10); // 列高地址
    OLED_WriteCmd(0x40); // 显示起始行
    OLED_WriteCmd(0x81); OLED_WriteCmd(0x7f); // 对比度
    OLED_WriteCmd(0xa1); // 段重映射
    OLED_WriteCmd(0xa6); // 正常显示
    OLED_WriteCmd(0xa8); OLED_WriteCmd(0x1f); // 多路复用 32
    OLED_WriteCmd(0xa4); // 全部显示恢复
    OLED_WriteCmd(0xd3); OLED_WriteCmd(0x00);
    OLED_WriteCmd(0xd5); OLED_WriteCmd(0xf0);
    OLED_WriteCmd(0xd9); OLED_WriteCmd(0x22);
    OLED_WriteCmd(0xda); OLED_WriteCmd(0x02);
    OLED_WriteCmd(0xdb); OLED_WriteCmd(0x49);
    OLED_WriteCmd(0x8d); OLED_WriteCmd(0x14); // 电荷泵
    OLED_WriteCmd(0xaf); // 显示开
#endif
}

void OLED_Clear(void) {
	#ifdef USE_MOCK
    printf("[OLED] Clear\n");
#else
    for (uint8_t i = 0; i < 4; i++) {
        OLED_SetPos(0, i);
        for (uint8_t j = 0; j < 128; j++)
           { OLED_WriteData(0x00);}
    }
	#endif
}

void OLED_ShowString(uint8_t x, uint8_t y, char *str) 
	{
		#ifdef USE_MOCK
    Mock_OLED_ShowString(y, str);   // 用 y 作为行号
#else
    while (*str) {
        OLED_SetPos(x, y);
        for (uint8_t i = 0; i < 6; i++) {
            OLED_WriteData(F6x8[(uint8_t)*str - 32][i]);
        }
        x += 6;
        str++;
    }
		#endif
}
	
